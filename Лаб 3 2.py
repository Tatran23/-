# Импортируем модуль random для генерации случайных чисел
import random

# Запрашиваем радиус мишени
R = float(input("Введите радиус мишени R: "))

# Выводим шапку таблицы
print("+----------+----------+----------+")
print("|    X     |    Y     | Результат|")
print("+----------+----------+----------+")

# Запускаем цикл на 10 итераций (10 выстрелов)
for i in range(10):
    # Генерируем случайную координату X в диапазоне от -R до R
    x = random.uniform(-R, R)
    # Генерируем случайную координату Y в диапазоне от -R до R
    y = random.uniform(-R, R)
    
    # Проверяем условие попадания в заштрихованную область (из ЛР2)
    if (x**2 + y**2 <= R**2) and ((x >= 0 and y >= x) or (x <= 0 and y <= x)):
        # Если попадание, сохраняем статус
        res = "  Yes   "
    else:
        # Если промах, сохраняем статус
        res = "  No    "
        
    # Выводим координаты и результат
    print("| {0: 7.4f} | {1: 7.4f} | {2} |".format(x, y, res))

# Выводим нижнюю границу таблицы
print("+----------+----------+----------+")