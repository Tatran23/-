import math

x = float(input("Введите значение аргумента x: "))

# Вычисление функции по участкам
if x < -4:
    y = -2
elif -4 <= x < 0:
    # Линейная функция (прямая)
    y = 0.25 * x
elif 0 <= x < 2:
    # Парабола
    y = x ** 2
else: # Для x >= 2
    # Прямая, пересекающая ось X в точке 10
    y = -0.5 * x + 5

# Вывод результата с 4 знаками после запятой (до десятитысячных)
print("X={0:.4f}   Y={1:.4f}".format(x, y))              