import math

x = float(input("Введите значение аргумента x: "))

# Вычисление значения функции y в зависимости от интервала
if x < -4:
    y = -2
elif -4 <= x < 2:
    # Уравнение дуги окружности с центром (-3, 4) и радиусом 5
    y = 4 - math.sqrt(25 - (x + 3)**2)
elif 2 <= x < 10:
    # Прямая, проходящая через точки (2, 4) и (10, 0)
    y = -0.5 * x + 5
else:
    # Прямая для x >= 10 (проходит через (10, 0) и (12, -2))
    # Здесь просто else: без условия
    y = -x + 10

# Вывод результата с 4 знаками после запятой (до десятитысячных)
print("X={0:.4f}   Y={1:.4f}".format(x, y))              