import math

print('Введите координаты X и Y для точки:')
x = float(input('X='))
y = float(input('Y='))

R1 = 5.0  # Внешний радиус
R2 = 3.0  # Внутренний радиус

flag = 0

# Проверка условия попадания:
# 1. Точка внутри внешнего круга (включая границу): x^2 + y^2 <= R1^2
# 2. Точка снаружи внутреннего круга (исключая границу): x^2 + y^2 > R2^2
# 3. Точка в 1-й или 3-й четверти (включая оси): x * y >= 0
if (x**2 + y**2 <= R1**2) and (x**2 + y**2 > R2**2) and (x * y >= 0):
    flag = 1
else:
    flag = 0

print("Точка X={0: 6.2f} Y={1: 6.2f}".format(x, y), end=" ")
if flag:
    print("попадает", end=" ")
else:
    print("не попадает", end=" ")